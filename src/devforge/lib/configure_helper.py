"""configure_helper — composes the configuration state file for /configure.

Owns the shape of `.devforge/configure.yaml`: 27 fields covering project
metadata, language/framework stacks, build/lint/type-check commands,
per-package stack records, workflow enforcement, AI attribution, Claude
tier settings, and AC verification parameters. `/configure` is the third
command in the 4-command pivot (init-forge → generate-docs → configure →
constitute).

Step 1 is fully implemented: FIELD_SCHEMA + ENUM_FIELDS populated,
emit_yaml/parse_yaml schema-driven, `reset` writes proper defaults,
read-init / read-docs / read-manifests / read-configs subcommands implemented.

Step 2 is fully implemented: _load / _dump / _state_transaction helpers,
all 27 setter subcommands (set-project-name, set-project-description,
set-project-type, set-primary-language, set-languages, set-frameworks,
set-architectures, set-error-handlings, set-api-layers, set-testings,
set-build-tools, set-build-commands, set-type-check-commands,
set-lint-commands, add-package-stack, set-project-structure,
set-dev-commands, set-architecture-details, set-workflow-enforcement,
set-ai-attribution, set-claude-tier-think, set-claude-tier-do,
set-claude-tier-verify, set-ac-verification-mode, set-ac-runtime-url,
set-ac-runtime-api-base, set-ac-runtime-cli-command). Cross-process
safety via POSIX file lock on <configure.yaml>.lock.

Step 3 is fully implemented: render-config (writes .devforge/project-config.json
with all 35 keys — 27 from configure.yaml + 5 from init.yaml + 3 derived),
verify (cross-checks all required fields populated + round-trip identity),
summary (human-readable field-by-field report to stdout). _write_json
atomic write helper parallel to _write_state.

Note on key count: project-config.json contains 35 keys, not 32 as stated
in CONFIGURE-PLAN.md Step 3 verify criteria. The actual breakdown is:
  27 from configure.yaml (FIELD_SCHEMA fields → UPPERCASE keys)
   5 from init.yaml (WORKSPACE_MODE, PROJECT_ROOT, PROJECT_STATE,
                     DEFAULT_BRANCH, PACKAGES_DETECTED)
   3 derived (WRAPPER_MODE_SECTION, COMMIT_ATTRIBUTION, AGENT_LIST)
The CONFIGURE-PLAN.md "32 keys" figure is incorrect. This implementation
renders all 35 keys as the correct contract.

Step 4 is fully implemented: substitute-templates walks CLAUDE.md +
.claude/agents/*.md (at --install-root), builds a full 25-key substitution
map from project-config.json + init.yaml, substitutes every {{KEY}}
placeholder, and writes files atomically (mkstemp + fsync + os.replace).
Substitution categories: (A) direct project-config.json keys, (B) 10
singular aliases of plural arrays (FRAMEWORK→FRAMEWORKS, etc.), (C) 2
composed values (PACKAGE_STACKS_SECTION markdown table, PROJECT_PATHS
comma-join), (D) UPPERCASE identity passthrough. Unknown placeholders
→ exit 2. State-management + styling rules live in constitution.md
(generated by /constitute), NOT in template substitution — agent files
reference constitution.md §Conventions for those project rules.

Architecture notes:

- The yaml IS the state. Each setter reads yaml from disk (or loads
  defaults if the file is absent), mutates an in-memory dict, and writes
  yaml back atomically via tempfile.mkstemp + os.replace in the same
  directory as the target.

- Field order in the emitted yaml is fixed (deterministic output for
  diff stability) and matches the source-of-truth schema below.

- `reset` writes a fresh defaults yaml; it does NOT delete the file.
  The artifact always exists post-reset. Idempotent: byte-identical on
  re-run.

- FIELD_SCHEMA contains 27 fields in locked order (project_name,
  project_description, project_type, primary_language, languages,
  frameworks, architectures, error_handlings, api_layers, testings,
  build_tools, build_commands, type_check_commands, lint_commands,
  package_stacks, project_structure, dev_commands, architecture_details,
  workflow_enforcement, ai_attribution, claude_tier_think, claude_tier_do,
  claude_tier_verify, ac_verification_mode, ac_runtime_url,
  ac_runtime_api_base, ac_runtime_cli_command).

- ENUM_FIELDS enforces allowed values at set-time for workflow_enforcement,
  ai_attribution, claude_tier_think, claude_tier_do, claude_tier_verify,
  ac_verification_mode.

- `default_state()` walks FIELD_SCHEMA and returns all 27 keys with
  type-appropriate defaults: scalars → None, arrays → [].

- `emit_yaml(state)` walks FIELD_SCHEMA in locked order, applying the same
  quoting/escaping rules as init_helper (double-quote scalars containing
  YAML special chars; null for None; block-style arrays).

- `parse_yaml(text)` is the inverse of emit_yaml. Raises YamlParseError
  on input outside the closed shape.

- `read-init` reads `.devforge/init.yaml` via init_helper.parse_yaml and
  emits JSON to stdout.

- `read-docs` parses Plan F sections from `docs/overview.md` and
  `docs/architecture.md` and emits structured JSON. Uses --install-root
  (default: parent of --devforge-dir).

- `read-manifests` reads `.devforge/index.json` and emits per-package
  script tables as JSON.

- `read-configs` reads `.devforge/index.json`, basename-matches config
  files in each package's file list, reads matched files, emits JSON.
  Uses --install-root (default: parent of --devforge-dir). Caps individual
  files at 10 KB.

- All 27 setters route through `_state_transaction(devforge_dir)` which
  holds an exclusive POSIX file lock around the read-modify-write cycle.
  Lock file: <configure.yaml>.lock. This prevents concurrent invocations
  from silently losing writes (append races are the primary concern for
  add-package-stack).

- Validation is set-time per-field shape. Validation helpers:
  _validate_scalar (non-empty string after strip),
  _validate_enum (enum membership check),
  _validate_string_array (comma-sep split + per-item validation),
  _validate_path_value (no newlines, non-empty),
  _validate_verbatim (non-empty after strip, preserves internal whitespace).

- `--devforge-dir` CLI argument (default: DEVFORGE_DIR env var, falling
  back to `.devforge`) is threaded through args to all subcommand handlers.

Stdlib only. No third-party dependencies. Targets Python 3.8+.
"""

